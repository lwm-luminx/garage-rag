//! GarageService's database facade, as the Rust workers reach it.
//!
//! [`Connection`] is GarageService over gRPC, on its Unix socket (`GARAGE_GRPC_SOCKET`) or a TCP
//! port, with the per-launch token as `x-garage-token`. Calls block: each runs to completion on the
//! connection's own runtime, so a worker needs no async code of its own.

use std::fmt;
use std::future::Future;
use std::path::PathBuf;

use hyper_util::rt::TokioIo;
use tonic::metadata::{Ascii, MetadataValue};
use tonic::service::Interceptor;
use tonic::service::interceptor::InterceptedService;
use tonic::transport::{Channel, Endpoint, Uri};

/// GarageService's messages and client (`proto/garage.proto`), generated by `protogen`.
#[allow(clippy::pedantic, clippy::doc_markdown)]
pub mod proto {
    include!("generated/garage.rs");
}

use proto::garage_service_client::GarageServiceClient;

/// The largest message either side sends (`service.server.MAX_REQUEST_BYTES`).
pub const MAX_MESSAGE_BYTES: usize = 256 * 1024 * 1024;

/// A facade call that failed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum FacadeError {
    /// What the call named does not exist: gRPC `NOT_FOUND`.
    NotFound(String),
    /// Anything else: the server unreachable, refusing the token, or failing.
    Failed(String),
}

impl fmt::Display for FacadeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NotFound(message) | Self::Failed(message) => f.write_str(message),
        }
    }
}

impl std::error::Error for FacadeError {}

impl From<tonic::Status> for FacadeError {
    fn from(status: tonic::Status) -> Self {
        let message = if status.message().is_empty() {
            format!("GarageService: {:?}", status.code())
        } else {
            format!("GarageService: {}", status.message())
        };
        if status.code() == tonic::Code::NotFound { Self::NotFound(message) } else { Self::Failed(message) }
    }
}

/// Where GarageService listens.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum GrpcTarget {
    /// Its Unix-domain socket.
    Socket(PathBuf),
    /// A TCP port, on loopback.
    Tcp { host: String, port: u16 },
}

/// Adds the per-launch token, when there is one, to every call.
#[derive(Clone)]
pub struct Token(Option<MetadataValue<Ascii>>);

impl Interceptor for Token {
    fn call(&mut self, mut request: tonic::Request<()>) -> Result<tonic::Request<()>, tonic::Status> {
        if let Some(token) = &self.0 {
            request.metadata_mut().insert("x-garage-token", token.clone());
        }
        Ok(request)
    }
}

/// The generated client, with the token added to each call.
pub type Client = GarageServiceClient<InterceptedService<Channel, Token>>;

/// A blocking connection to GarageService.
pub struct Connection {
    runtime: tokio::runtime::Runtime,
    client: Client,
}

impl Connection {
    /// Connects to GarageService. `token` is the per-launch `GARAGE_GRPC_TOKEN`, when one is set.
    ///
    /// # Errors
    ///
    /// [`FacadeError::Failed`] when there is no server to connect to.
    pub fn connect(target: &GrpcTarget, token: Option<&str>) -> Result<Self, FacadeError> {
        let runtime = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .map_err(|error| FacadeError::Failed(format!("cannot start the gRPC runtime: {error}")))?;
        let channel = runtime.block_on(connect(target))?;
        let token = match token.filter(|token| !token.is_empty()) {
            Some(token) => Some(
                MetadataValue::try_from(token)
                    .map_err(|_| FacadeError::Failed("the gRPC token is not valid metadata".into()))?,
            ),
            None => None,
        };
        let client = GarageServiceClient::with_interceptor(channel, Token(token))
            .max_decoding_message_size(MAX_MESSAGE_BYTES)
            .max_encoding_message_size(MAX_MESSAGE_BYTES);
        Ok(Self { runtime, client })
    }

    /// Runs one call to completion: `call` is handed a client and returns the call's future.
    ///
    /// # Errors
    ///
    /// The call's own status, as a [`FacadeError`].
    pub fn call<T, F>(&self, call: impl FnOnce(Client) -> F) -> Result<T, FacadeError>
    where
        F: Future<Output = Result<tonic::Response<T>, tonic::Status>>,
    {
        Ok(self.runtime.block_on(call(self.client.clone()))?.into_inner())
    }

    /// Runs one server-streaming call, handing `each` every message as it arrives, until the
    /// stream ends or `each` returns false.
    ///
    /// # Errors
    ///
    /// The call's own status, as a [`FacadeError`].
    pub fn stream<T, F>(
        &self,
        call: impl FnOnce(Client) -> F,
        mut each: impl FnMut(T) -> bool,
    ) -> Result<(), FacadeError>
    where
        F: Future<Output = Result<tonic::Response<tonic::Streaming<T>>, tonic::Status>>,
    {
        self.runtime.block_on(async {
            let mut stream = call(self.client.clone()).await?.into_inner();
            while let Some(item) = stream.message().await? {
                if !each(item) {
                    break;
                }
            }
            Ok(())
        })
    }
}

async fn connect(target: &GrpcTarget) -> Result<Channel, FacadeError> {
    let unreachable = |error: tonic::transport::Error| {
        let source = std::error::Error::source(&error).map_or_else(String::new, |source| format!(": {source}"));
        FacadeError::Failed(format!("cannot reach GarageService at {}: {error}{source}", describe(target)))
    };
    match target {
        #[cfg(unix)]
        GrpcTarget::Socket(path) => {
            let path = path.clone();
            // The URI is required by the API and ignored by the connector.
            Endpoint::from_static("http://garage")
                .connect_with_connector(tower::service_fn(move |_: Uri| {
                    let path = path.clone();
                    async move { Ok::<_, std::io::Error>(TokioIo::new(tokio::net::UnixStream::connect(path).await?)) }
                }))
                .await
                .map_err(unreachable)
        }
        #[cfg(not(unix))]
        GrpcTarget::Socket(_) => Err(FacadeError::Failed(format!(
            "cannot reach GarageService at {}: Unix-domain sockets need Unix",
            describe(target)
        ))),
        GrpcTarget::Tcp { host, port } => {
            let host = if host.contains(':') { format!("[{host}]") } else { host.clone() };
            let endpoint = Endpoint::from_shared(format!("http://{host}:{port}"))
                .map_err(|error| FacadeError::Failed(format!("bad GarageService address: {error}")))?;
            endpoint.connect().await.map_err(unreachable)
        }
    }
}

/// `target` as messages name it.
#[must_use]
pub fn describe(target: &GrpcTarget) -> String {
    match target {
        GrpcTarget::Socket(path) => format!("unix:{}", path.display()),
        GrpcTarget::Tcp { host, port } => format!("{host}:{port}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_absent_server_is_reported_with_its_address() {
        let target = GrpcTarget::Socket(PathBuf::from("/no/such/garage.sock"));
        let Err(FacadeError::Failed(message)) = Connection::connect(&target, None) else { panic!("connected") };
        assert!(message.contains("unix:/no/such/garage.sock"), "{message}");
    }
}
